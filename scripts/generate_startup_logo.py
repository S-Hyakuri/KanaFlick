"""Keep the system first frame's paths, local gradients and inset in sync with LogoDrawable.
Run after editing the static tile/signal artwork. The first frame intentionally has no ribbon/wordmark.
"""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
s=(root/'app/src/main/java/com/hyakuri/kanaflick/ui/startup/LogoDrawable.kt').read_text(encoding='utf-8-sig')
parts=re.findall(r'Part\("([^"]+)", "(#[A-Fa-f0-9]+)", "(#[A-Fa-f0-9]+)"\)',s)
motion=(root/'app/src/main/java/com/hyakuri/kanaflick/ui/startup/LogoMotion.kt').read_text(encoding='utf-8-sig')
scale=float(re.search(r'const val ART_SCALE = ([0-9.]+)f', motion)[1])
offset=float(re.search(r'const val ART_OFFSET_X = (-?[0-9.]+)f', motion)[1])
inset=1536*(1-scale)/2
xml=['<!-- Generated by scripts/generate_startup_logo.py. -->','<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" android:width="288dp" android:height="288dp" android:viewportWidth="1536" android:viewportHeight="1536">',f'    <group android:scaleX="{scale:g}" android:scaleY="{scale:g}" android:translateX="{inset+offset*scale:g}" android:translateY="{inset:g}">']
for data,begin,end in parts:
    xy=[(float(x),float(y)) for x,y in re.findall(r'(-?[\d.]+),(-?[\d.]+)',data)]
    xs,ys=zip(*xy)
    xml += [f'        <path android:pathData="{data}">','            <aapt:attr name="android:fillColor">',f'                <gradient android:startX="{min(xs):g}" android:startY="{min(ys):g}" android:endX="{max(xs):g}" android:endY="{max(ys):g}" android:startColor="{begin}" android:endColor="{end}" android:type="linear" />','            </aapt:attr>','        </path>']
xml+=['    </group>','</vector>']
(root/'app/src/main/res/drawable/startup_logo.xml').write_text('\n'.join(xml)+'\n',encoding='utf-8')
print('Updated',len(parts),'paths')
