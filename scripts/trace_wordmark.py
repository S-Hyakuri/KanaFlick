"""Trace the supplied wordmark into code-native paths; no font substitution or bitmap shipped.
Only the brand-name band is used. Pixel loops use a 7-sample contour average, 0.35px simplification and bounded quadratic joins.
Run with Python + Pillow + numpy. Source: docs/font.png (user supplied).
"""
from pathlib import Path
from collections import defaultdict
import numpy as np
from PIL import Image
root = Path(__file__).resolve().parents[1]
a = np.asarray(Image.open(root/'docs/font.png').convert('RGB'), dtype=np.int16)[:245]
mask = (a[:,:,2]-a[:,:,0]>65) & (a[:,:,1]>65) & (a[:,:,0]<155)
h,w=mask.shape
edges=defaultdict(list)
for y,x in zip(*np.nonzero(mask)):
    x,y=int(x),int(y)
    if y==0 or not mask[y-1,x]: edges[(x,y)].append((x+1,y))
    if x==w-1 or not mask[y,x+1]: edges[(x+1,y)].append((x+1,y+1))
    if y==h-1 or not mask[y+1,x]: edges[(x+1,y+1)].append((x,y+1))
    if x==0 or not mask[y,x-1]: edges[(x,y+1)].append((x,y))
def rdp(points, eps=.35):
    if len(points)<3:return points
    p=np.asarray(points,dtype=float); d=p[-1]-p[0]; den=np.hypot(*d)
    ds=np.abs(d[0]*(p[:,1]-p[0,1])-d[1]*(p[:,0]-p[0,0]))/den if den else np.linalg.norm(p-p[0],axis=1)
    i=int(ds.argmax())
    return rdp(points[:i+1],eps)[:-1]+rdp(points[i:],eps) if ds[i]>eps else [points[0],points[-1]]
loops=[]
while edges:
    start=next(iter(edges)); p=start; pts=[p]
    while True:
        q=edges[p].pop()
        if not edges[p]:del edges[p]
        p=q
        if p==start:break
        pts.append(p)
    area=sum(pts[i][0]*pts[(i+1)%len(pts)][1]-pts[(i+1)%len(pts)][0]*pts[i][1] for i in range(len(pts)))/2
    if abs(area)<20:continue
    # Smooth the full-resolution contour BEFORE simplification, not just its corners.
    contour=np.asarray(pts,dtype=float)
    contour=sum(np.roll(contour,k,axis=0) for k in range(-3,4))/7
    pts=[tuple(p) for p in contour]
    mid=max(range(len(pts)),key=lambda i:(pts[i][0]-pts[0][0])**2+(pts[i][1]-pts[0][1])**2)
    pts=rdp(pts[:mid+1])[:-1]+rdp(pts[mid:]+[pts[0]])[:-1]
    bounds=(min(x for x,y in pts),min(y for x,y in pts),max(x for x,y in pts),max(y for x,y in pts))
    loops.append((pts,bounds,area))
# Merge holes into the corresponding solid glyph. Separate the three decorative signals.
outer=[p for p in loops if p[2]>0]; holes=[p for p in loops if p[2]<0]
def data(pts):
    # Smooth the raster staircase with quadratic joins; preserve winding and holes.
    joins=[]
    for i,p in enumerate(pts):
        prev,nxt=pts[i-1],pts[(i+1)%len(pts)]
        def near(q):
            dx,dy=q[0]-p[0],q[1]-p[1]
            distance=(dx*dx+dy*dy)**.5
            t=min(.5,2.0/distance) if distance else 0
            return p[0]+dx*t,p[1]+dy*t
        joins.append((near(prev),p,near(nxt)))
    d=f'M {joins[0][0][0]:.2f},{joins[0][0][1]:.2f}'
    for start,p,end in joins:
        d+=f' L {start[0]:.2f},{start[1]:.2f} Q {p[0]:g},{p[1]:g} {end[0]:.2f},{end[1]:.2f}'
    return d+' Z'
items=[]
for pts,b,area in sorted(outer,key=lambda x:x[1][0]):
    d=data(pts)
    for hp,hb,ha in holes:
        if b[0]<=hb[0] and b[1]<=hb[1] and b[2]>=hb[2] and b[3]>=hb[3]:d+=' '+data(hp)
    group=2 if b[3]<100 else (0 if b[0]<430 else 1)
    items.append((d,group,b))
lines=['package com.hyakuri.kanaflick.ui.startup','', '// Generated by scripts/trace_wordmark.py from user-supplied docs/font.png.', 'internal object WordmarkPaths {', '    data class Glyph(val data: String, val group: Int)', '    val glyphs = listOf(']
for d,g,b in items:lines.append(f'        Glyph("{d}", {g}),')
lines+=['    )','}']
(root/'app/src/main/java/com/hyakuri/kanaflick/ui/startup/WordmarkPaths.kt').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print([(g,b) for _,g,b in items]); print('vertices',sum(len(p[0]) for p in loops))
